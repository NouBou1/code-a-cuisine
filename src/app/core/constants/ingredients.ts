/**
 * Finds suggestions for a typed ingredient name.
 * Matches at the start of the name come first, then matches at the start of a later word.
 * @param query - Typed text.
 * @param exclude - Names already on the list, ignored case-insensitively.
 * @param limit - Maximum number of suggestions.
 * @returns Matching ingredient names.
 */
export function suggestIngredients(
  query: string,
  exclude: readonly string[] = [],
  limit = MAX_SUGGESTIONS,
): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const taken = new Set(exclude.map((name) => name.toLowerCase()));
  const candidates = INGREDIENT_SUGGESTIONS.filter((name) => !taken.has(name.toLowerCase()));
  const starts = candidates.filter((name) => name.toLowerCase().startsWith(q));
  const words = candidates.filter(
    (name) => !starts.includes(name) && name.toLowerCase().includes(' ' + q),
  );
  return [...starts, ...words].slice(0, limit);
}
